"""Extract the blue vector paths of Thiel et al. 2020, Fig. 3b,d.

The plotted abscissa is |net current density| in A/cm2; the sign is restored
from the potential relative to the turning point, positive for anodic current.
This is figure digitization, not the authors' original polarization data.
"""

import csv
import configparser
import hashlib
import json
from pathlib import Path

import numpy as np
import pdfplumber

ROOT = Path(__file__).resolve().parent
PDF = ROOT.parents[1] / "literature" / "raw" / "thiel2020.pdf"


def extract(page, bbox, log_min, log_max, e_min, e_max):
    x0, top, x1, bottom = bbox
    candidates = [
        c for c in page.curves
        if isinstance(c.get("stroking_color"), tuple)
        and c["stroking_color"][0] < 0.1
        and c["stroking_color"][2] > 0.6
        and len(c["pts"]) > 100
        and x0 <= c["x0"] <= x1
        and top <= c["top"] <= bottom
        and c["bottom"] <= bottom
    ]
    if len(candidates) != 1:
        raise RuntimeError(f"Expected one data path, found {len(candidates)}")
    pts = np.asarray(candidates[0]["pts"])
    potential = e_max - (pts[:, 1] - top) / (bottom - top) * (e_max - e_min)
    log_current = log_min + (pts[:, 0] - x0) / (x1 - x0) * (log_max - log_min)
    magnitude = 10 ** log_current * 1e4
    equilibrium = float(np.median(potential[pts[:, 0] < pts[:, 0].min() + 0.3]))
    signed = np.where(potential > equilibrium, magnitude, -magnitude)
    keep = np.abs(potential - equilibrium) >= 0.002
    potential, signed = potential[keep], signed[keep]
    order = np.argsort(potential)
    potential, signed = potential[order], signed[order]
    # One value per small potential bin avoids duplicated voltages along the flat turn.
    bins = np.round(potential / 0.002).astype(int)
    points = [(float(np.median(potential[bins == b])), float(np.median(signed[bins == b])))
              for b in np.unique(bins)]
    points.append((equilibrium, 0.0))
    points.sort()
    table = np.asarray(points)
    correction = np.maximum.accumulate(table[:, 1]) - table[:, 1]
    table[:, 1] = np.maximum.accumulate(table[:, 1])
    return table, {"equilibrium_V_AgAgCl": equilibrium,
                   "min_V": float(table[:, 0].min()), "max_V": float(table[:, 0].max()),
                   "points": len(table), "max_monotonic_correction_A_m2": float(correction.max())}


def main():
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "models").mkdir(exist_ok=True)
    mapping = {
        "hy80": ((332.005, 143.521, 502.545, 261.327), -6, -2, -1.0, -0.3),
        "nab": ((332.005, 298.3113, 502.5452, 416.1155), -8, -2, -1.0, 0.0),
    }
    meta = {"source": "Thiel et al., JMSE 2020, 8, 105, Fig. 3b,d; DOI 10.3390/jmse8020105",
            "pdf_sha256": hashlib.sha256(PDF.read_bytes()).hexdigest(),
            "reference": "Ag/AgCl as published in Thiel 2020",
            "sign": "positive = net anodic current from metal into water",
            "caution": "Digitized curves; linear interpolation and endpoint linear extrapolation. Near-zero turn bridged through zero. Branch labels in the source figure are inconsistent with the usual net-anodic sign convention; sign follows potential relative to corrosion potential."}
    tables = {}
    with pdfplumber.open(PDF) as doc:
        page = doc.pages[4]
        for name, mapping_args in mapping.items():
            table, info = extract(page, *mapping_args)
            tables[name] = table
            meta[name] = info
            with (ROOT / "data" / f"{name}_polarization.csv").open("w", newline="", encoding="ascii") as f:
                w = csv.writer(f); w.writerow(["potential_V_AgAgCl", "net_anodic_current_A_m2"]); w.writerows(table)
    (ROOT / "data" / "polarization_provenance.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    config = configparser.RawConfigParser()
    config.optionxform = str
    config.read_string('[parameters]\n' + (ROOT / 'parameters.properties').read_text(encoding='ascii'))
    lines = ['// Generated by extract_polarization.py. Edit parameters.properties, not this file.',
             'public final class ICCPInputs {', '  public static final String[][] PARAMETERS = {']
    for key, value in config['parameters'].items():
        lines.append('    {' + json.dumps(key) + ', ' + json.dumps(value) + '},')
    lines.append('  };')
    for name, table in tables.items():
        lines.append(f'  public static final String[][] {name.upper()} = {{')
        lines += ['    {"%.12g", "%.12g"},' % tuple(row) for row in table]
        lines.append('  };')
    lines.append('}')
    (ROOT / 'ICCPInputs.java').write_text('\n'.join(lines)+'\n', encoding='ascii')
    print(json.dumps(meta, indent=2))


if __name__ == "__main__":
    main()
