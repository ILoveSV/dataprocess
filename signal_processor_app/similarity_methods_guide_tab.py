def _plot_bg_subtract(fig, t, x, y, name):
    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(t, x, label='实验 x', color='#1f77b4')
    ax1.plot(t, y, label='背景 b', color='#ff7f0e', alpha=0.8)
    ax1.set_title(f'{name} - 原始信号', fontsize=10)
    ax1.legend(fontsize=8); ax1.grid(alpha=0.3)

    # 直接相减
    y_direct = x - y
    # 归一化相减
    x_n = (x - x.mean()) / (x.std() + 1e-10)
    y_n = (y - y.mean()) / (y.std() + 1e-10)
    y_norm = x_n - y_n
    # 互相关对齐
    corr = np.correlate(x - x.mean(), y - y.mean(), mode='full')
    shift = np.argmax(corr) - (len(y) - 1)
    y_aligned = np.roll(y, shift)
    y_xcorr = x - y_aligned

    ax2 = fig.add_subplot(2, 2, 2)
    ax2.plot(t, y_direct, label='直接相减', color='#d62728', alpha=0.7)
    ax2.plot(t, y_norm, label='归一化相减', color='#9467bd', alpha=0.7)
