def _plot_distance(fig, t, x, y, name):
    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(t, x, label='x', color='#1f77b4')
    ax1.plot(t, y, label='y', color='#ff7f0e', alpha=0.8)
    ax1.set_title(f'{name} - 信号对比', fontsize=10)
    ax1.set_xlabel('时间 (s)'); ax1.set_ylabel('幅值')
    ax1.legend(fontsize=8); ax1.grid(alpha=0.3)

    ax2 = fig.add_subplot(2, 2, 2)
    diff = x - y
    ax2.plot(t, diff, color='#d62728', linewidth=0.8)
    ax2.fill_between(t, diff, 0, alpha=0.3, color='#d62728')
    ax2.set_title(f'差异 x-y（L2={np.linalg.norm(diff):.3f}, L1={np.sum(np.abs(diff)):.3f}）', fontsize=10)
    ax2.set_xlabel('时间 (s)'); ax2.set_ylabel('差异')
    ax2.grid(alpha=0.3)

    ax3 = fig.add_subplot(2, 2, 3)
    ax3.scatter(x[::5], y[::5], s=4, alpha=0.5)
    lim = max(abs(x).max(), abs(y).max()) * 1.1
    ax3.plot([-lim, lim], [-lim, lim], 'r--', alpha=0.5)
    ax3.set_xlim(-lim, lim); ax3.set_ylim(-lim, lim)
    ax3.set_xlabel('x'); ax3.set_ylabel('y')
    ax3.set_title('散点图（理想为 y=x 对角线）', fontsize=10)
    ax3.grid(alpha=0.3); ax3.set_aspect('equal')

    ax4 = fig.add_subplot(2, 2, 4)
    p_values = [1, 2, 3, 5, 10, 50]
    dists = [np.sum(np.abs(diff) ** p) ** (1.0 / p) for p in p_values]
    ax4.bar(range(len(p_values)), dists, color='#9467bd')
    ax4.set_xticks(range(len(p_values)))
    ax4.set_xticklabels([f'p={p}' for p in p_values])
    ax4.set_title('不同 p 下的 Lp 距离（闵可夫斯基族）', fontsize=10)
    ax4.set_ylabel('距离值')
    ax4.grid(alpha=0.3, axis='y')


def _plot_cosine(fig, t, x, y, name):
    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(t, x, label='x')
    ax1.plot(t, y, label='y', alpha=0.8)
    ax1.set_title(f'{name} - 信号对比', fontsize=10)
    ax1.legend(fontsize=8); ax1.grid(alpha=0.3)

    ax2 = fig.add_subplot(2, 2, 2)
    # 三种信号：原信号、缩放、反向
    y_scaled = 5 * y
    y_reverse = -y
    cos_xy = float(np.dot(x, y) / (np.linalg.norm(x) * np.linalg.norm(y) + 1e-10))
    cos_xs = float(np.dot(x, y_scaled) / (np.linalg.norm(x) * np.linalg.norm(y_scaled) + 1e-10))
    cos_xr = float(np.dot(x, y_reverse) / (np.linalg.norm(x) * np.linalg.norm(y_reverse) + 1e-10))
    labels = ['x vs y', 'x vs 5y', 'x vs -y']
    vals = [cos_xy, cos_xs, cos_xr]
    colors = ['#2ca02c', '#1f77b4', '#d62728']
    bars = ax2.bar(labels, vals, color=colors)
    ax2.axhline(0, color='k', linewidth=0.5)
    ax2.set_ylim(-1.1, 1.1)
    ax2.set_title(f'余弦相似度（缩放不变: x vs 5y 仍 ≈ {cos_xs:.3f}）', fontsize=10)
    ax2.grid(alpha=0.3, axis='y')
    for b, v in zip(bars, vals):
        ax2.text(b.get_x() + b.get_width() / 2, v + 0.03 if v >= 0 else v - 0.08,
                 f'{v:.3f}', ha='center', fontsize=9)

    ax3 = fig.add_subplot(2, 2, 3)
    # 向量夹角示意（2D 投影）
    # 用前两个样本作为 2D 向量示意
    v1 = np.array([x[0], x[1]])
