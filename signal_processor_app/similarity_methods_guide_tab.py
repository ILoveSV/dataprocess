def _plot_stat_avg(fig, t, x, y, name):
    # 模拟多组背景数据
    rng = np.random.RandomState(42)
    bg_groups = [y + 0.2 * rng.randn(len(y)) for _ in range(10)]
    # 注入脉冲干扰
    bg_groups[3][100] += 5.0
    bg_groups[7][200] += 4.0

    ax1 = fig.add_subplot(2, 2, 1)
    for i, bg in enumerate(bg_groups[:5]):
        ax1.plot(t, bg, alpha=0.5, linewidth=0.5)
    ax1.set_title(f'{name} - 多组背景数据', fontsize=10)
    ax1.grid(alpha=0.3)

    mean_bg = np.mean(bg_groups, axis=0)
    median_bg = np.median(bg_groups, axis=0)
    rms_bg = np.sqrt(np.mean(np.square(bg_groups), axis=0))

    ax2 = fig.add_subplot(2, 2, 2)
    ax2.plot(t, mean_bg, label='均值', color='#1f77b4')
    ax2.plot(t, median_bg, label='中位数', color='#ff7f0e', alpha=0.8)
    ax2.plot(t, rms_bg, label='RMS', color='#2ca02c', alpha=0.8)
    ax2.set_title('三种统计平均对比', fontsize=10)
    ax2.legend(fontsize=8); ax2.grid(alpha=0.3)

    ax3 = fig.add_subplot(2, 2, 3)
    # 离群点影响：均值被脉冲拉偏
    ax3.plot(t, mean_bg, label=f'均值（受脉冲影响）\nL2偏移={np.linalg.norm(mean_bg-median_bg):.3f}',
             color='#d62728', alpha=0.7)
    ax3.plot(t, median_bg, label='中位数（鲁棒）', color='#2ca02c', alpha=0.7)
    ax3.set_title('离群点影响对比', fontsize=10)
    ax3.legend(fontsize=8); ax3.grid(alpha=0.3)

    ax4 = fig.add_subplot(2, 2, 4)
    # 噪声方差下降
    noise_orig = np.std(bg_groups[0])
    noise_mean = np.std(bg_groups[0] - mean_bg)
    noise_median = np.std(bg_groups[0] - median_bg)
    labels = ['原始噪声', '均值后', '中位数后']
    vals = [noise_orig, noise_mean, noise_median]
    bars = ax4.bar(labels, vals, color=['#999', '#1f77b4', '#ff7f0e'])
    ax4.set_title('噪声抑制效果（理论 1/√N）', fontsize=10)
    ax4.grid(alpha=0.3, axis='y')
    for b, v in zip(bars, vals):
        ax4.text(b.get_x() + b.get_width() / 2, v + max(vals) * 0.02,
                 f'{v:.4f}', ha='center', fontsize=9)


