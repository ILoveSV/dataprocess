def _plot_freq_kl(fig, t, x, y, fs, name):
    from signal_processing import get_spectrum
    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(t, x, label='x')
    ax1.plot(t, y, label='y', alpha=0.8)
    ax1.set_title(f'{name} - 时域信号', fontsize=10)
    ax1.legend(fontsize=8); ax1.grid(alpha=0.3)

    sx, sy = get_spectrum(x, fs), get_spectrum(y, fs)
    freqs = np.fft.rfftfreq(len(x), d=1 / fs)
    sx_n = sx / (np.sum(sx) + 1e-10)
    sy_n = sy / (np.sum(sy) + 1e-10)
    kl_xy = np.sum(sx_n * np.log((sx_n + 1e-10) / (sy_n + 1e-10)))
    kl_yx = np.sum(sy_n * np.log((sy_n + 1e-10) / (sx_n + 1e-10)))
    m = 0.5 * (sx_n + sy_n)
    js = 0.5 * np.sum(sx_n * np.log((sx_n + 1e-10) / (m + 1e-10))) + \
         0.5 * np.sum(sy_n * np.log((sy_n + 1e-10) / (m + 1e-10)))

    ax2 = fig.add_subplot(2, 2, 2)
    ax2.plot(freqs, sx_n, label='P(x)', color='#1f77b4')
    ax2.plot(freqs, sy_n, label='P(y)', color='#ff7f0e', alpha=0.8)
    ax2.set_title('归一化频谱分布', fontsize=10)
    ax2.set_xlabel('频率 (Hz)'); ax2.set_ylabel('概率')
    ax2.legend(fontsize=8); ax2.grid(alpha=0.3)

    ax3 = fig.add_subplot(2, 2, 3)
    labels = ['KL(x||y)', 'KL(y||x)', 'JS']
    vals = [kl_xy, kl_yx, js]
    colors = ['#d62728', '#ff7f0e', '#2ca02c']
    bars = ax3.bar(labels, vals, color=colors)
    ax3.set_title('KL/JS 散度对比（KL 不对称）', fontsize=10)
    ax3.grid(alpha=0.3, axis='y')
    for b, v in zip(bars, vals):
        ax3.text(b.get_x() + b.get_width() / 2, v + max(vals) * 0.02,
                 f'{v:.4f}', ha='center', fontsize=9)

    ax4 = fig.add_subplot(2, 2, 4)
    ax4.text(0.5, 0.7, f'KL(x||y) = {kl_xy:.4f}\nKL(y||x) = {kl_yx:.4f}\nJS = {js:.4f}\n\n'
             'KL 非对称 ≠ 距离\nJS 对称 + 有界 + 度量',
             ha='center', va='center', fontsize=10,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#d1ecf1', edgecolor='#17a2b8'))
    ax4.text(0.5, 0.2, '误导：归一化丢失幅度\nx 与 100x 的 KL=0',
             ha='center', va='center', fontsize=10,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#fff3cd', edgecolor='#ffc107'))
    ax4.set_axis_off()


def _plot_freq_centroid(fig, t, x, y, fs, name):
    from signal_processing import get_spectrum
    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(t, x, label='x')
    ax1.plot(t, y, label='y', alpha=0.8)
    ax1.set_title(f'{name} - 时域信号', fontsize=10)
    ax1.legend(fontsize=8); ax1.grid(alpha=0.3)

    sx, sy = get_spectrum(x, fs), get_spectrum(y, fs)
    freqs = np.fft.rfftfreq(len(x), d=1 / fs)
    cx = np.sum(freqs * sx) / (np.sum(sx) + 1e-10)
    cy = np.sum(freqs * sy) / (np.sum(sy) + 1e-10)

    ax2 = fig.add_subplot(2, 2, 2)
    ax2.plot(freqs, sx, label='|Sx|', color='#1f77b4')
    ax2.axvline(cx, color='#1f77b4', linestyle='--', label=f'重心 x={cx:.1f}Hz')
    ax2.plot(freqs, sy, label='|Sy|', color='#ff7f0e', alpha=0.8)
    ax2.axvline(cy, color='#ff7f0e', linestyle='--', label=f'重心 y={cy:.1f}Hz')
    ax2.set_title(f'频谱重心对比（Δ={abs(cx-cy):.2f}Hz）', fontsize=10)
    ax2.set_xlabel('频率 (Hz)'); ax2.set_ylabel('幅度')
    ax2.legend(fontsize=8); ax2.grid(alpha=0.3)

    ax3 = fig.add_subplot(2, 2, 3)
    # 重心 + 带宽
    bx = np.sqrt(np.sum((freqs - cx) ** 2 * sx) / (np.sum(sx) + 1e-10))
    by = np.sqrt(np.sum((freqs - cy) ** 2 * sy) / (np.sum(sy) + 1e-10))
    labels = ['重心 cx', '重心 cy', '带宽 bx', '带宽 by']
    vals = [cx, cy, bx, by]
    colors = ['#1f77b4', '#ff7f0e', '#1f77b4', '#ff7f0e']
    bars = ax3.bar(labels, vals, color=colors)
    for b, a in zip(bars, [0.7, 0.7, 0.4, 0.4]):
        b.set_alpha(a)
    ax3.set_title('重心与带宽对比', fontsize=10)
    ax3.grid(alpha=0.3, axis='y')
    for b, v in zip(bars, vals):
        ax3.text(b.get_x() + b.get_width() / 2, v + max(vals) * 0.02,
                 f'{v:.1f}', ha='center', fontsize=9)

    ax4 = fig.add_subplot(2, 2, 4)
    ax4.text(0.5, 0.7, f'重心 cx = {cx:.2f} Hz\ncy = {cy:.2f} Hz\n\n'
             '• 能量加权平均频率\n• 单标量特征\n• 反映能量集中频段',
             ha='center', va='center', fontsize=10,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#d1ecf1', edgecolor='#17a2b8'))
