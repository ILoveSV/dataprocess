    ax2.set_ylim(0, 1.1); ax2.legend(fontsize=8); ax2.grid(alpha=0.3)

    ax3 = fig.add_subplot(2, 2, 3)
    ax3.plot(f, pxx, label='Pxx', color='#1f77b4')
    ax3.plot(f, pyy, label='Pyy', color='#ff7f0e', alpha=0.8)
    ax3.set_title('功率谱密度对比', fontsize=10)
    ax3.set_xlabel('频率 (Hz)'); ax3.set_ylabel('PSD')
    ax3.legend(fontsize=8); ax3.grid(alpha=0.3)

    ax4 = fig.add_subplot(2, 2, 4)
    ax4.text(0.5, 0.7, f'谱相干性均值 = {coh.mean():.3f}\n\n'
             '• 频域线性依赖\n• 仅线性关系\n• 频率分辨\n• Welch 方法估计',
             ha='center', va='center', fontsize=10,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#d1ecf1', edgecolor='#17a2b8'))
