def _plot_nmi(fig, t, x, y, name):
    from sklearn.metrics import mutual_info_score
    from scipy.stats import entropy

    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(t, x, label='x')
    ax1.plot(t, y, label='y', alpha=0.8)
    ax1.set_title(f'{name} - 信号对比', fontsize=10)
    ax1.legend(fontsize=8); ax1.grid(alpha=0.3)

    ax2 = fig.add_subplot(2, 2, 2)
    # 不同 bins 下 NMI
    bins_list = [5, 10, 20, 30, 50]
    nmis = []
    for bins in bins_list:
        xd = np.digitize(x, np.linspace(x.min(), x.max(), bins))
        yd = np.digitize(y, np.linspace(y.min(), y.max(), bins))
        mi = mutual_info_score(xd, yd)
        hx = entropy(np.bincount(xd, minlength=bins + 1))
        hy = entropy(np.bincount(yd, minlength=bins + 1))
        nmi = 2 * mi / (hx + hy) if hx > 0 and hy > 0 else 0
        nmis.append(nmi)
    ax2.plot(bins_list, nmis, 'o-', color='#9467bd')
    ax2.set_title('NMI 随 bins 数变化', fontsize=10)
    ax2.set_xlabel('bins 数'); ax2.set_ylabel('NMI')
    ax2.grid(alpha=0.3)

    ax3 = fig.add_subplot(2, 2, 3)
    # 2D 直方图
    h, xe, ye = np.histogram2d(x, y, bins=30)
    im = ax3.imshow(h.T, origin='lower', aspect='auto', cmap='Blues',
                    extent=[xe[0], xe[-1], ye[0], ye[-1]])
    ax3.set_title('联合分布 p(x,y)', fontsize=10)
    ax3.set_xlabel('x'); ax3.set_ylabel('y')
    fig.colorbar(im, ax=ax3, fraction=0.046)

    ax4 = fig.add_subplot(2, 2, 4)
    # 非线性依赖 vs 皮尔逊
    y_nl = x ** 2
    r_p = float(np.corrcoef(x, y_nl)[0, 1])
    xd = np.digitize(x, np.linspace(x.min(), x.max(), 20))
    yd = np.digitize(y_nl, np.linspace(y_nl.min(), y_nl.max(), 20))
    mi = mutual_info_score(xd, yd)
    hx = entropy(np.bincount(xd, minlength=21))
    hy = entropy(np.bincount(yd, minlength=21))
    nmi_nl = 2 * mi / (hx + hy) if hx > 0 and hy > 0 else 0
    ax4.text(0.5, 0.65, f'非线性依赖案例：y=x²\n\n皮尔逊 r = {r_p:.3f}\nNMI = {nmi_nl:.3f}\n\nNMI 揭示依赖\n皮尔逊失效',
             ha='center', va='center', fontsize=10,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#d4edda', edgecolor='#28a745'))
    ax4.set_axis_off()


