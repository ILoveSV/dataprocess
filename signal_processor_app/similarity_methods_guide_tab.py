def _plot_dtw(fig, t, x, y, name):
    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(t, x, label='x')
    # 制造变长信号
    y_stretched = np.interp(t, t[::2], y[::2])
    ax1.plot(t, y_stretched, label='y (时间拉伸)', alpha=0.8)
    ax1.set_title(f'{name} - 信号对比', fontsize=10)
    ax1.legend(fontsize=8); ax1.grid(alpha=0.3)

    # 简化 DTW 路径（降采样后计算）
    x_small = x[::20]
    y_small = y_stretched[::20]
    n, m = len(x_small), len(y_small)
    D = np.inf * np.ones((n + 1, m + 1))
    D[0, 0] = 0
    for i in range(1, n + 1):
        for j in range(1, m + 1):
            cost = abs(x_small[i - 1] - y_small[j - 1])
            D[i, j] = cost + min(D[i - 1, j], D[i, j - 1], D[i - 1, j - 1])

    ax2 = fig.add_subplot(2, 2, 2)
    im = ax2.imshow(D[1:, 1:], origin='lower', aspect='auto', cmap='viridis')
    ax2.set_title('DTW 代价矩阵', fontsize=10)
    ax2.set_xlabel('y 索引'); ax2.set_ylabel('x 索引')
    fig.colorbar(im, ax=ax2, fraction=0.046)

    # 回溯最优路径
    path = []
    i, j = n, m
    while i > 0 and j > 0:
        path.append((i - 1, j - 1))
        candidates = [(D[i - 1, j - 1], i - 1, j - 1),
                      (D[i - 1, j], i - 1, j),
                      (D[i, j - 1], i, j - 1)]
        _, i, j = min(candidates)
    path = np.array(path)
    ax2.plot(path[:, 1], path[:, 0], 'r-', linewidth=1.5, label='最优路径')
    ax2.legend(fontsize=8)

    ax3 = fig.add_subplot(2, 2, 3)
    # 对齐后的信号
    aligned_y = np.array([y_small[j] for _, j in path[::-1]])
    aligned_x = np.array([x_small[i] for i, _ in path[::-1]])
    ax3.plot(aligned_x, label='x (对齐)', color='#1f77b4')
    ax3.plot(aligned_y, label='y (对齐)', color='#ff7f0e', alpha=0.8)
    ax3.set_title('DTW 对齐后信号', fontsize=10)
    ax3.legend(fontsize=8); ax3.grid(alpha=0.3)

    ax4 = fig.add_subplot(2, 2, 4)
    ax4.text(0.5, 0.7, f'DTW 距离 = {D[n, m]:.3f}\n\n关键特性：\n• 一对多匹配\n• 非度量（无三角不等式）\n• O(nm) 复杂度',
             ha='center', va='center', fontsize=11,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#d1ecf1', edgecolor='#17a2b8'))
    ax4.text(0.5, 0.2, '误导：DTW 距离小\n≠ 信号相似\n（可能仅是路径病态）',
             ha='center', va='center', fontsize=10,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#fff3cd', edgecolor='#ffc107'))
    ax4.set_axis_off()


def _plot_ssim(fig, t, x, y, name):
    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(t, x, label='x')
    ax1.plot(t, y, label='y', alpha=0.8)
    ax1.set_title(f'{name} - 信号对比', fontsize=10)
    ax1.legend(fontsize=8); ax1.grid(alpha=0.3)

    # 计算 SSIM 三分量
    mu_x, mu_y = x.mean(), y.mean()
    sigma_x, sigma_y = x.std(), y.std()
    sigma_xy = np.mean((x - mu_x) * (y - mu_y))
    c1, c2 = 1e-10, 1e-10
    luminance = (2 * mu_x * mu_y + c1) / (mu_x ** 2 + mu_y ** 2 + c1)
    contrast_struct = (2 * sigma_xy + c2) / (sigma_x ** 2 + sigma_y ** 2 + c2)
    ssim = luminance * contrast_struct

    ax2 = fig.add_subplot(2, 2, 2)
    labels = ['亮度项', '对比度结构项', 'SSIM']
    vals = [luminance, contrast_struct, ssim]
    colors = ['#1f77b4', '#ff7f0e', '#2ca02c']
    bars = ax2.bar(labels, vals, color=colors)
    ax2.set_ylim(-1.1, 1.1)
    ax2.set_title(f'SSIM 三分量（总 SSIM={ssim:.3f}）', fontsize=10)
    ax2.grid(alpha=0.3, axis='y')
    for b, v in zip(bars, vals):
        ax2.text(b.get_x() + b.get_width() / 2, v + 0.03 if v >= 0 else v - 0.08,
                 f'{v:.3f}', ha='center', fontsize=9)

    ax3 = fig.add_subplot(2, 2, 3)
    # 滑窗 SSIM
    win = 50
    ssim_curve = []
    for i in range(0, len(x) - win, 10):
        xs, ys = x[i:i + win], y[i:i + win]
        mx, my = xs.mean(), ys.mean()
        sx, sy = xs.std(), ys.std()
        sxy = np.mean((xs - mx) * (ys - my))
        l = (2 * mx * my + c1) / (mx ** 2 + my ** 2 + c1)
        cs = (2 * sxy + c2) / (sx ** 2 + sy ** 2 + c2)
        ssim_curve.append(l * cs)
    ax3.plot(np.arange(len(ssim_curve)) * 10, ssim_curve, color='#9467bd')
    ax3.set_title('滑窗 SSIM 曲线', fontsize=10)
    ax3.set_xlabel('样本'); ax3.set_ylabel('局部 SSIM')
    ax3.grid(alpha=0.3); ax3.set_ylim(-1.1, 1.1)

    ax4 = fig.add_subplot(2, 2, 4)
    ax4.text(0.5, 0.7, f'σ_x={sigma_x:.4f}\nσ_y={sigma_y:.4f}\nC1=C2=1e-10\n（本程序默认）',
             ha='center', va='center', fontsize=10,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#d1ecf1', edgecolor='#17a2b8'))
    ax4.text(0.5, 0.25, '误导：C1,C2 过小\n低能量信号 SSIM 不稳定\n一维信号缺乏图像感知依据',
             ha='center', va='center', fontsize=10,
             transform=ax4.transAxes,
             bbox=dict(boxstyle='round', facecolor='#fff3cd', edgecolor='#ffc107'))
    ax4.set_axis_off()


