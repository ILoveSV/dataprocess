def md_to_html(text):
    """简易 Markdown 转 HTML（支持标题、列表、表格、强调、代码、公式占位）"""
    import re
    lines = text.split('\n')
    out = []
    in_table = False
    in_list = False
    for line in lines:
        esc = html_mod.escape(line)
        # 数学公式占位（不实际渲染 LaTeX，仅保留原文）
        esc = esc.replace('$', '<span style="color:#c7254e;font-family:Consolas,monospace;">').replace('$', '</span>', 1) \
            if '$' in esc else esc
        if line.startswith('# '):
            if in_list: out.append("</ul>"); in_list = False
            if in_table: out.append("</table>"); in_table = False
            out.append(f"<h1>{esc[2:]}</h1>")
        elif line.startswith('## '):
            if in_list: out.append("</ul>"); in_list = False
            if in_table: out.append("</table>"); in_table = False
            out.append(f"<h2>{esc[3:]}</h2>")
        elif line.startswith('### '):
            if in_list: out.append("</ul>"); in_list = False
            if in_table: out.append("</table>"); in_table = False
            out.append(f"<h3>{esc[4:]}</h3>")
        elif line.startswith('> '):
            if in_list: out.append("</ul>"); in_list = False
            if in_table: out.append("</table>"); in_table = False
            out.append(f"<blockquote>{esc[2:]}</blockquote>")
        elif line.startswith('• ') or line.startswith('- '):
            if in_table: out.append("</table>"); in_table = False
            if not in_list:
                out.append("<ul>"); in_list = True
            out.append(f"<li>{esc[2:]}</li>")
        elif line.startswith('|') and '---' not in line:
            if in_list: out.append("</ul>"); in_list = False
            cells = [c.strip() for c in line.strip('|').split('|')]
            if not in_table:
                out.append("<table border='1' cellpadding='4' cellspacing='0' style='border-collapse:collapse;'>")
                in_table = True
                out.append("<tr>" + "".join(f"<th>{c}</th>" for c in cells) + "</tr>")
            else:
                out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
        elif line.strip() == '' and in_table:
            out.append("</table>"); in_table = False
        elif line.strip() == '' and in_list:
            out.append("</ul>"); in_list = False
        elif line.strip() == '---':
            if in_list: out.append("</ul>"); in_list = False
            if in_table: out.append("</table>"); in_table = False
            out.append("<hr>")
        elif line.strip():
            if in_list: out.append("</ul>"); in_list = False
            if in_table: out.append("</table>"); in_table = False
            out.append(f"<p>{esc}</p>")
    if in_list: out.append("</ul>")
    if in_table: out.append("</table>")
    body = "\n".join(out)
    # 简单公式高亮
    return f"""<html><head><meta charset='utf-8'>
<style>
body {{ font-family: 'Microsoft YaHei', sans-serif; font-size: 13px; line-height: 1.6; padding: 12px; }}
h1 {{ color: #2c3e50; border-bottom: 2px solid #3498db; padding-bottom: 6px; font-size: 18px; }}
h2 {{ color: #2980b9; margin-top: 16px; font-size: 15px; }}
h3 {{ color: #16a085; font-size: 13px; }}
blockquote {{ border-left: 4px solid #f39c12; background: #fef9e7; padding: 6px 12px; margin: 8px 0; color: #7d6608; }}
code {{ background: #f4f4f4; padding: 1px 4px; border-radius: 3px; font-family: Consolas, monospace; }}
ul {{ margin: 6px 0; padding-left: 24px; }}
li {{ margin: 3px 0; }}
hr {{ border: none; border-top: 1px dashed #bbb; margin: 16px 0; }}
p {{ margin: 6px 0; }}
</style></head><body>{body}</body></html>"""


