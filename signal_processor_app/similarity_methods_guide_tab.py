def _make_signals(n=500, fs=1000.0, seed=42):
    """生成一对示例信号用于数形结合展示"""
    rng = np.random.RandomState(seed)
    t = np.arange(n) / fs
    x = 1.0 * np.sin(2 * np.pi * 50 * t) + 0.3 * np.sin(2 * np.pi * 120 * t)
    # y 为 x 加噪声并稍微变化
    y = 0.95 * np.sin(2 * np.pi * 50 * t + 0.05) + 0.25 * np.sin(2 * np.pi * 120 * t) + 0.1 * rng.randn(n)
    return t, x, y, fs


